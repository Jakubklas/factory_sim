// Generate helm/factory-sim/values.yaml from plant.json, platform.json, inventory.json.
// Usage: IMAGE_REGISTRY=... PLANT_CONFIG=./config cargo run -p codegen --bin gen_helm_values
//
// plantConfig is intentionally absent — it is passed at deploy time via:
//   helm upgrade --install ... --set-file plantConfig=config/plant.json
// This keeps a single source of truth for plant config with no transformation or duplication.

use std::fmt::Write as _;
use plant_config::loader::load_plant_config;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let config_dir = std::env::var("PLANT_CONFIG")
        .unwrap_or_else(|_| "./config".to_string());
    let registry = std::env::var("IMAGE_REGISTRY")
        .unwrap_or_else(|_| "ghcr.io/jakubklas/factory_sim".to_string());

    let plant_path = format!("{}/plant.json", config_dir);
    let plant = load_plant_config(&plant_path)?;

    let platform_json = std::fs::read_to_string("./deploy/platform.json")?;
    let platform: serde_json::Value = serde_json::from_str(&platform_json)?;

    let inventory_json = std::fs::read_to_string("./deploy/inventory.json")?;
    let inventory: serde_json::Value = serde_json::from_str(&inventory_json)?;

    let backend_target = platform["components"]["backend"]["deploy_target"]
        .as_str().unwrap_or("ec2");
    let backend_port: u16 = platform["components"]["backend"]["ports"][0]
        .as_str().unwrap_or("3001").parse().unwrap_or(3001);
    let backend_host = inventory["devices"][backend_target]["host"]
        .as_str().unwrap_or("localhost");

    let frontend_target = platform["components"]["frontend"]["deploy_target"]
        .as_str().unwrap_or("ec2");

    let mut out = String::new();
    writeln!(out, "# Auto-generated by: just helm-gen")?;
    writeln!(out, "# Do not edit by hand — edit config/plant.json or deploy/platform.json, then re-run helm-gen.")?;
    writeln!(out)?;
    writeln!(out, "registry: {}", registry)?;
    writeln!(out, "imageTag: latest")?;
    writeln!(out)?;
    writeln!(out, "plcs:")?;
    for plc in plant.plcs.iter().filter(|p| p.simulated) {
        if let Some(target) = &plc.deploy_target {
            // PLCs on the same node as the backend use cluster DNS → ClusterIP.
            // PLCs on a different node have a Tailscale URI in plant.json → LoadBalancer
            // binds the port on that node's host interface so the Tailscale hostname resolves.
            let service_type = if target == backend_target { "ClusterIP" } else { "LoadBalancer" };
            writeln!(out, "  - id: {}", plc.plc_id)?;
            writeln!(out, "    port: {}", plc.port)?;
            writeln!(out, "    deployTarget: {}", target)?;
            writeln!(out, "    serviceType: {}", service_type)?;
        }
    }
    writeln!(out)?;
    writeln!(out, "backend:")?;
    writeln!(out, "  port: {}", backend_port)?;
    writeln!(out, "  deployTarget: {}", backend_target)?;
    writeln!(out)?;
    writeln!(out, "frontend:")?;
    writeln!(out, "  deployTarget: {}", frontend_target)?;
    writeln!(out, "  beUrl: \"http://{}:{}\"", backend_host, backend_port)?;

    print!("{}", out);
    Ok(())
}
